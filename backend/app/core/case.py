"""
The domain-neutral layer the merge adds *above* ClaimEvidence.

Why this exists: the original project's best decision was a single
evidence shape (ClaimEvidence) that both the synthetic generator and the
real pipeline produce, so nothing downstream changes when a backend is
swapped. The merged project verifies two kinds of case -- motor claims
and commercial underwriting -- so it generalises that idea one level up
instead of replacing it:

  Case       one thing being verified (a claim, or a company applying
             for cover), plus every assertion extracted for it.
  Assertion  one checkable fact: "garage GSTIN = 29ABCDE1234F1Z5, from
             bill page 1, via OCR". Every extraction path (OCR, local
             model, hosted LLM, synthetic generator) emits these, tagged
             with where they came from and how sensitive they are.

Domain *views* (ClaimEvidence for motor claims, UnderwritingEvidence
for underwriting) are built from or alongside these, which is why the
9 original claim rules, the fusion trainer and every original test keep
working unchanged.

Status: real, used by the underwriting pipeline and the privacy guard.
The motor-claim pipeline still builds ClaimEvidence directly;
`assertions_from_claim_evidence` below shows the mapping and is used for
the audit/explanation side, not yet for scoring.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Union

from app.ml.domain import ClaimEvidence


class CaseType(str, Enum):
    MOTOR_CLAIM = "motor_claim"
    UNDERWRITING = "underwriting"


class Sensitivity(str, Enum):
    """Set by *where data came from*, never by what it looks like.

    RESTRICTED  claimant/applicant-submitted material (photos, bills,
                submitted statements). Must never reach a free-tier
                hosted API -- see services/privacy_guard.py.
    PUBLIC      published material (annual reports, news, policy
                wordings published by the insurer).
    SYNTHETIC   generated by this project for training/evaluation.
    """
    RESTRICTED = "restricted"
    PUBLIC = "public"
    SYNTHETIC = "synthetic"


class ExtractionPath(str, Enum):
    OCR = "ocr"
    LOCAL_MODEL = "local_model"
    HOSTED_LLM = "hosted_llm"
    RULES = "rules"
    MOCK = "mock"
    SYNTHETIC = "synthetic"
    MANUAL = "manual"


@dataclass(frozen=True)
class SourceRef:
    document: str
    page: int | None = None
    locator: str | None = None  # chunk id, bounding box, table cell, ...


Value = Union[str, int, float, bool]


@dataclass
class Assertion:
    case_id: str
    entity: str          # "garage", "company", "vehicle_photo", ...
    attribute: str       # "gstin", "revenue", "damage_location", ...
    value: Value
    source: SourceRef
    path: ExtractionPath
    sensitivity: Sensitivity
    unit: str | None = None      # "INR", "INR_crore", ...
    period: str | None = None    # "FY2025", "2026-03-31", ...
    confidence: float = 1.0

    @property
    def key(self) -> tuple[str, str, str | None]:
        """Two assertions with the same key are claims about the same
        fact and can be cross-checked against each other."""
        return (self.entity, self.attribute, self.period)


@dataclass
class Case:
    case_id: str
    case_type: CaseType
    assertions: list[Assertion] = field(default_factory=list)

    def add(self, assertion: Assertion) -> None:
        if assertion.case_id != self.case_id:
            raise ValueError(f"assertion belongs to case {assertion.case_id}, not {self.case_id}")
        self.assertions.append(assertion)

    def find(self, entity: str | None = None, attribute: str | None = None, period: str | None = None) -> list[Assertion]:
        return [
            a for a in self.assertions
            if (entity is None or a.entity == entity)
            and (attribute is None or a.attribute == attribute)
            and (period is None or a.period == period)
        ]

    def conflicting_pairs(self) -> list[tuple[Assertion, Assertion]]:
        """Pairs of assertions with the same key but different values from
        different documents -- the raw material of cross-verification.
        Numeric tolerance is applied by the rule packs, not here."""
        pairs: list[tuple[Assertion, Assertion]] = []
        by_key: dict[tuple, list[Assertion]] = {}
        for a in self.assertions:
            by_key.setdefault(a.key, []).append(a)
        for group in by_key.values():
            for i, a in enumerate(group):
                for b in group[i + 1:]:
                    if a.source.document != b.source.document and a.value != b.value:
                        pairs.append((a, b))
        return pairs


def assertions_from_claim_evidence(ev: ClaimEvidence, sensitivity: Sensitivity = Sensitivity.RESTRICTED) -> list[Assertion]:
    """Express a motor claim's ClaimEvidence as assertions. Synthetic
    claims (those with ground truth set) are tagged SYNTHETIC regardless
    of the argument, so they can be sent to hosted models for
    benchmarking without tripping the privacy guard."""
    if ev.injected_inconsistency is not None:
        sensitivity = Sensitivity.SYNTHETIC
    path = ExtractionPath.SYNTHETIC if sensitivity == Sensitivity.SYNTHETIC else ExtractionPath.MOCK

    def a(entity: str, attribute: str, value: Value, document: str, unit: str | None = None) -> Assertion:
        return Assertion(ev.claim_id, entity, attribute, value, SourceRef(document), path, sensitivity, unit=unit)

    out = [
        a("incident", "described_type", ev.described_incident_type.value, "description"),
        a("incident", "date", ev.incident_date.isoformat(), "claim_form"),
        a("vehicle_photo", "damage_location", ev.photo_damage_location.value, "photo"),
        a("vehicle_photo", "damage_severity", ev.photo_damage_severity.value, "photo"),
        a("vehicle_photo", "phash", ev.photo_hash, "photo"),
        a("repair_bill", "total", ev.bill_total_inr, "bill", unit="INR"),
    ]
    if ev.photo_capture_date:
        out.append(a("vehicle_photo", "capture_date", ev.photo_capture_date.isoformat(), "photo"))
    if ev.garage_gstin:
        out.append(a("garage", "gstin", ev.garage_gstin, "bill"))
    for item in ev.bill_line_items:
        out.append(a("repair_bill", f"line_item:{item.category}", item.cost_inr, "bill", unit="INR"))
    return out
